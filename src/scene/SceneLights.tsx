/**
 * 场景打光。人体场景与单腺体场景共用，保证同一个器官在两处长得一样。
 *
 * 之前是 `ambientLight 0.7` + 两盏平行光。0.7 的环境光会把所有形体的明暗
 * 冲平 —— 这是"器官看起来像塑料糖果"的一半原因（另一半是表面太光滑）。
 * 环境光是各向同性的，给得越多，物体越没有体积。
 *
 * 现在是常规的三点布光加一盏半球光：
 *
 * - **半球光**代替大部分环境光。它按法线朝向在天光色与地色之间插值，
 *   朝上的面偏冷亮、朝下的面偏暖暗，本身就带方向信息，不会压平形体。
 * - **主光**从右前上方来，负责绝大部分明暗与浆膜高光。
 * - **补光**从左前方来，很弱，只把暗部从纯黑里提出来，不参与造型。
 * - **轮廓光**从后方来，在器官边缘勾一道亮边，把它从深色背景里剥离。
 *   在这种暗底场景里，轮廓光比补光更能"提精致度"。
 *
 * 真正的环境光只留一点点，防止背光面死黑。
 */
export function SceneLights() {
  return (
    <>
      <hemisphereLight args={['#e8f1f8', '#232c38', 0.85]} />
      <ambientLight intensity={0.16} />

      {/* 主光 */}
      <directionalLight position={[2.2, 3, 2.6]} intensity={1.7} color="#fff4e8" />
      {/* 补光 */}
      <directionalLight position={[-2.6, 0.8, 1.6]} intensity={0.55} color="#c2d8ff" />
      {/* 轮廓光 */}
      <directionalLight position={[-0.8, 1.6, -3]} intensity={0.95} color="#cfe2ff" />
    </>
  )
}
